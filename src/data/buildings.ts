const buildingMap = Object.fromEntries(
  buildings.map((building) => [
    building.id,
    building,
  ]),
) as Record<BuildingId, Building>

export const getBuilding = (
  buildingId: BuildingId,
): Building => {
  return buildingMap[buildingId]
}

export const getBuildingHitPoints = (
  buildingId: BuildingId,
  level: number,
): number => {
  const building = getBuilding(buildingId)

  const safeLevel = Math.min(
    building.maxLevel,
    Math.max(
      0,
      Math.round(level),
    ),
  )

  return building.hitPoints[safeLevel] ?? 0
}